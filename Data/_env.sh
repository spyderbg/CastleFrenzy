#!/usr/bin/env bash
# Shared environment for the Data/ build scripts.
# Linux equivalent of the project's config.bat + setenv.bat + make_prepare.bat.
#
# Every Data/*.sh script sources this file first. Values can be overridden by
# exporting the same variable before invoking a script, e.g.:
#     OUTPUT_PATH=build/linux-release/assets ./make_data.sh

_data_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

# Project layout (mirrors setenv.bat).
PROJECT_PATH="$(cd -- "$_data_dir/.." && pwd)"
PROJECT_DATA_PATH="$PROJECT_PATH/Data"
PROJECT_TOOLS_PATH="$PROJECT_PATH/tools"
PROJECT_SRC_PATH="$PROJECT_PATH/Src"

# Runtime asset directory (mirrors setenv.bat OUTPUT_PATH=build\bin).
# Kept inside the lowercase build/ tree so tools/linux/build_resources.py accepts it.
OUTPUT_PATH="${OUTPUT_PATH:-$PROJECT_PATH/build/bin}"
HEADERS_OUT_PATH="${HEADERS_OUT_PATH:-$PROJECT_SRC_PATH/Autogenerated}"

# Build version (mirrors config.bat).
VERSION_MAJOR="${VERSION_MAJOR:-1}"
VERSION_MINOR="${VERSION_MINOR:-1}"
VERSION_BUILD="${VERSION_BUILD:-0}"

# Pack build order (mirrors make_prepare.bat DATA_BUILD_FLOW).
DATA_BUILD_FLOW=(Strings Fonts Sprites Scenes Sounds Effects)

# Texture format for the Linux build: "png" (editable) or "pvr" (legacy).
RESOURCE_TEXTURE_FORMAT="${RESOURCE_TEXTURE_FORMAT:-png}"

# Java used by the StringParser / SoundConfigExporter tools.
JAVA_BIN="${JAVA_BIN:-java}"
