#!/usr/bin/env bash

# Linux equivalent of Data/Sounds/_make.bat
# Exports the sound configuration, packages each sound group into an audio
# pack, and generates the sound ID header.
#
# Usage: _make.sh [clean|no_bar]
#   clean    - clean artifacts and exit
#   (none)   - clean, build, and archive
#   no_bar   - build the config export only, without archiving
set -euo pipefail
shopt -s nullglob

source "$(dirname -- "${BASH_SOURCE[0]}")/../_env.sh"

PACK_NAME="Sounds"
dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
[[ "$OUTPUT_PATH" == /* ]] || OUTPUT_PATH="$PWD/$OUTPUT_PATH"
[[ "$HEADERS_OUT_PATH" == /* ]] || HEADERS_OUT_PATH="$PWD/$HEADERS_OUT_PATH"
cd "$dir"

GENERATED_HEADER="sounds.h"
SOUND_CONFIGURATION_FILE="SoundConfiguration.xls"
SOUND_CONFIGURATION_OUT="sounds_config.xml"
arg="${1:-}"

# Move a generated header into HEADERS_OUT_PATH only if it is new or changed
# (mirrors the FC "no differences" check in _make.bat). Preserves the target's
# original file mode so a umask-0 environment does not flip the executable bit.
install_header() {
    local src="$1" base target orig_mode=""
    base="$(basename "$src" .h)"
    target="$HEADERS_OUT_PATH/$base.h"
    if [[ -e "$target" ]]; then
        orig_mode="$(stat -c '%a' "$target")"
    fi
    if [[ ! -e "$target" ]]; then
        mv -f "$src" "$HEADERS_OUT_PATH/"
    elif ! cmp -s "$src" "$target"; then
        mv -f "$src" "$HEADERS_OUT_PATH/"
    else
        rm -f "$src"
    fi
    if [[ -n "$orig_mode" && -e "$target" ]]; then
        chmod "$orig_mode" "$target"
    fi
}

# Clean data (mirrors _make.bat: clean when arg is "clean" or empty).
if [[ "$arg" == "clean" ]]; then
    OUTPUT_PATH="$OUTPUT_PATH" bash "$dir/_clean.sh"
    exit 0
fi
if [[ "$arg" == "" ]]; then
    OUTPUT_PATH="$OUTPUT_PATH" bash "$dir/_clean.sh"
fi

echo
echo "**************************************************************"
echo "   Make $PACK_NAME"
echo "**************************************************************"

# Export the sound configuration (SoundConfiguration.xls -> sounds_config.xml).
"$PYTHON_BIN" "$PROJECT_TOOLS_PATH/sound_config_exporter.py" "$SOUND_CONFIGURATION_FILE" "$SOUND_CONFIGURATION_OUT"
mkdir -p "$OUTPUT_PATH/config"
mv -f "$SOUND_CONFIGURATION_OUT" "$OUTPUT_PATH/config/"

# Archive (mirrors the "not no_bar" section of _make.bat).
if [[ "$arg" != "no_bar" ]]; then
    echo
    echo "**************************************************************"
    echo "   Archiving $PACK_NAME"
    echo "**************************************************************"

    mkdir -p "$HEADERS_OUT_PATH"
    # Package each sound group into an audio pack (flattening the .wav files).
    d=""
    for d in */; do
        d="${d%/}"
        [[ "$d" == "bin" ]] && continue
        (
            cd "$dir/$d"
            mkdir -p bin
            rm -f "$OUTPUT_PATH/audio_$d.pack"
            find . -path ./bin -prune -o -name "*.wav" -exec cp -f {} bin/ \;
            ( cd bin && "$PYTHON_BIN" "$PROJECT_TOOLS_PATH/zip_directory.py" "$OUTPUT_PATH/audio_$d.pack" "." --stored )
            rm -rf bin
        )
    done

    # Generate the sound ID header. ListSoundFiles.exe has no Linux binary, so
    # replicate its output exactly: Music then SFX, each sorted by filename,
    # uppercased, in the same include-guarded layout the tool emits.
    "$PYTHON_BIN" - "$OUTPUT_PATH" <<'PY'
import sys, zipfile
from pathlib import Path
out = Path(sys.argv[1])
names = []
for group in ("Music", "SFX"):
    pack = out / f"audio_{group}.pack"
    if pack.is_file():
        with zipfile.ZipFile(pack) as z:
            names.extend(Path(info.filename).stem.upper() for info in sorted(z.infolist(), key=lambda i: i.filename.lower()))
sep = "//" + "-" * 105
lines = [
    sep,
    "// Auto-generated file from ListSoundFiles.exe",
    sep,
    "#ifndef __AUTOGENERATED_SOUNDS_H_INCLUDED__",
    "#define __AUTOGENERATED_SOUNDS_H_INCLUDED__",
    sep,
    sep,
    "",
]
lines += [f"#define {name:<50}{i}" for i, name in enumerate(names)]
lines += ["", sep, sep, "#endif //__AUTOGENERATED_SOUNDS_H_INCLUDED__"]
Path("sounds.h").write_text("\n".join(lines) + "\n")
print(f"Generated sounds.h with {len(names)} sound IDs")
PY

    install_header "$GENERATED_HEADER"
fi
