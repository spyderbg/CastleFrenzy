// Game data locations and maintenance commands shared by the editor tools:
// StreamingAssets/GameData (what the Unity game loads), Build/bin (C++ game data) and Data/Sprites (sprite sources).
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace CastleFrenzy.EditorTools
{
    public static class GameDataTools
    {
        public static string ProjectRoot { get { return Path.GetFullPath(Path.Combine(Application.dataPath, "../..")).Replace('\\', '/'); } }
        public static string UnityData { get { return Path.Combine(Application.streamingAssetsPath, "GameData").Replace('\\', '/'); } }
        public static string BuildBin { get { return ProjectRoot + "/Build/bin"; } }
        public static string SpriteSources { get { return ProjectRoot + "/Data/Sprites"; } }
        public static string IdsFolder { get { return Application.dataPath + "/CastleFrenzy/Scripts/Autogenerated"; } }
        /// <summary>Backups of files the editor tools overwrite (like .auroramx/ and .level-editor/ for the web tools).</summary>
        public static string BackupDir { get { return ProjectRoot + "/.unity-editor/backups"; } }

        /// <summary>Absolute path of a GameData-relative file in the Unity copy.</summary>
        public static string UnityPath(string relative) { return UnityData + "/" + relative.Replace('\\', '/'); }

        /// <summary>Other copies of the same file that the C++ build and the original tools use.</summary>
        public static IEnumerable<string> MirrorPaths(string relative)
        {
            relative = relative.Replace('\\', '/');
            yield return BuildBin + "/" + relative;
            if (relative.StartsWith("Sprites/")) yield return SpriteSources + "/" + relative.Substring("Sprites/".Length);
        }

        /// <summary>Writes the Unity copy and every existing mirror (keeps the three sprite YAML copies identical).</summary>
        public static List<string> WriteGameFile(string relative, byte[] bytes, bool mirror = true)
        {
            List<string> written = new List<string>();
            string main = UnityPath(relative);
            Directory.CreateDirectory(Path.GetDirectoryName(main));
            WriteAtomic(main, bytes);
            written.Add(main);
            if (mirror)
                foreach (string m in MirrorPaths(relative))
                    if (File.Exists(m)) { WriteAtomic(m, bytes); written.Add(m); }
            return written;
        }

        public static void WriteAtomic(string path, byte[] bytes)
        {
            string tmp = path + ".tmp";
            File.WriteAllBytes(tmp, bytes);
            if (File.Exists(path))
            {
                string backupDir = BackupDir;
                Directory.CreateDirectory(backupDir);
                File.Copy(path, backupDir + "/" + Path.GetFileName(path) + "." + DateTime.Now.ToString("yyyyMMdd-HHmmss") + ".bak", true);
                File.Delete(path);
            }
            File.Move(tmp, path);
        }

        [MenuItem("Castle Frenzy/Game Data/Sync From Build|bin", priority = 200)]
        public static void SyncFromBuildBin()
        {
            if (!Directory.Exists(BuildBin)) { EditorUtility.DisplayDialog("Castle Frenzy", "Build/bin was not found next to the Unity project.", "OK"); return; }
            int copied = 0;
            foreach (string src in Directory.GetFiles(BuildBin, "*", SearchOption.AllDirectories))
            {
                string rel = src.Substring(BuildBin.Length + 1).Replace('\\', '/');
                if (rel.EndsWith(".mp4") || rel.EndsWith(".meta")) continue;
                string dst = UnityPath(rel);
                if (File.Exists(dst) && new FileInfo(dst).Length == new FileInfo(src).Length && File.ReadAllBytes(dst).SequenceEqual(File.ReadAllBytes(src))) continue;
                Directory.CreateDirectory(Path.GetDirectoryName(dst));
                File.Copy(src, dst, true);
                copied++;
            }
            AssetDatabase.Refresh();
            Debug.Log("[CastleFrenzy] Synced " + copied + " changed file(s) from Build/bin into StreamingAssets/GameData.");
        }

        [MenuItem("Castle Frenzy/Game Data/Regenerate Sprite IDs", priority = 201)]
        public static void RegenerateSpriteIdsMenu()
        {
            string report = RegenerateSpriteIds();
            AssetDatabase.Refresh();
            Debug.Log("[CastleFrenzy] " + report);
        }

        /// <summary>
        /// Rebuilds Ids_Menu/Ingame/Fonts.cs from the sprite YAML names, following Sprites.sprcmd and AuroraMX's
        /// ExportFramesID/ExportAnimsID rule: PREFIX + (name or index), non-identifier characters to '_', upper case.
        /// </summary>
        public static string RegenerateSpriteIds()
        {
            string sprcmd = SpriteSources + "/Sprites.sprcmd";
            string spriteRoot = SpriteSources;
            if (!File.Exists(sprcmd)) return "Sprites.sprcmd not found in Data/Sprites.";
            Dictionary<string, List<KeyValuePair<string, int>>> headers = new Dictionary<string, List<KeyValuePair<string, int>>>();
            Dictionary<string, HashSet<string>> seen = new Dictionary<string, HashSet<string>>();
            SpriteDocument doc = null;
            foreach (string raw in File.ReadAllLines(sprcmd))
            {
                string line = raw.Trim();
                Match m = Regex.Match(line, "^Load\\(\"([^\"]+)\"\\)");
                if (m.Success)
                {
                    string rel = m.Groups[1].Value.Replace('\\', '/');
                    string unityCopy = UnityPath("Sprites/" + rel);
                    string path = File.Exists(unityCopy) ? unityCopy : spriteRoot + "/" + rel;
                    doc = SpriteDocument.Parse(File.ReadAllText(path));
                    continue;
                }
                m = Regex.Match(line, "^Export(Frames|Anims)ID\\(\"([^\"]+)\",\\s*\"([^\"]+)\"\\s*(?:,\\s*([A-Z|]+))?");
                if (!m.Success || doc == null) continue;
                string header = Path.GetFileNameWithoutExtension(m.Groups[2].Value.Replace('\\', '/'));
                string prefix = m.Groups[3].Value;
                bool upper = m.Groups[4].Value.Contains("TOUPPER");
                if (!headers.ContainsKey(header)) { headers[header] = new List<KeyValuePair<string, int>>(); seen[header] = new HashSet<string>(); }
                List<string> names = m.Groups[1].Value == "Frames" ? doc.frames.Select(f => f.name).ToList() : doc.animations.Select(a => a.name).ToList();
                for (int i = 0; i < names.Count; i++)
                {
                    string name = Regex.Replace(prefix + (string.IsNullOrEmpty(names[i]) ? i.ToString() : names[i]), "[^a-zA-Z0-9_]", "_");
                    if (upper) name = name.ToUpperInvariant();
                    if (seen[header].Add(name)) headers[header].Add(new KeyValuePair<string, int>(name, i));
                }
            }
            int total = 0;
            foreach (var h in headers)
            {
                StringBuilder sb = new StringBuilder();
                sb.Append("// Generated by Castle Frenzy > Game Data > Regenerate Sprite IDs (from Data/Sprites/Sprites.sprcmd). Do not edit.\n");
                sb.Append("// ").Append(h.Key).Append(".h\nnamespace CastleFrenzy\n{\n    public static partial class Ids\n    {\n");
                foreach (var kv in h.Value) sb.Append("        public const int ").Append(kv.Key).Append(" = ").Append(kv.Value).Append(";\n");
                sb.Append("    }\n}\n");
                string outPath = IdsFolder + "/Ids_" + h.Key + ".cs";
                string text = sb.ToString();
                if (!File.Exists(outPath) || File.ReadAllText(outPath) != text) File.WriteAllText(outPath, text);
                total += h.Value.Count;
            }
            return "Regenerated " + total + " sprite IDs in " + headers.Count + " file(s).";
        }

        /// <summary>Enters Play mode and jumps straight into a level/day (see LaunchOptions).</summary>
        public static void PlayLevel(int level, int day, int difficulty, bool endless, bool skipCutscene)
        {
            if (EditorApplication.isPlaying) EditorApplication.isPlaying = false;
            string args = endless ? "-cf-endless" : "-cf-level " + level + " -cf-day " + day;
            args += " -cf-difficulty " + difficulty + (skipCutscene ? " -cf-skip-cutscene" : "");
            Directory.CreateDirectory(Path.GetDirectoryName(LaunchOptions.EditorRequestPath));
            File.WriteAllText(LaunchOptions.EditorRequestPath, args);
            BuildScript.EnsureMainScene();
            EditorApplication.isPlaying = true;
        }
    }
}
