#!/usr/bin/env python3
"""Generate the Unity port's string and sound ID tables from the source data, without the C++ headers.

    StringIds.cs   <- Data/Strings/fortress_defender_strings.xls
                      IDs are SHEET_ROWID (upper case) numbered in workbook order, read with the same parser as
                      tools/string_parser.py, so they match the shipped string tables.
    Ids_sounds.cs  <- Unity/Assets/StreamingAssets/GameData/audio_Music.pack, then audio_SFX.pack
                      IDs are the upper-case file names numbered in archive order, the order in which the game
                      registers the packs (CApplication) and looks sounds up (BaseSoundManager).

Sprite IDs come from the Unity editor (Castle Frenzy > Game Data > Regenerate Sprite IDs). Ids_Common.cs is a
frozen copy of the legacy Common.h, which has no sprite source.

    python3 tools/unity/gen_ids.py            # rewrite the C# files that changed
    python3 tools/unity/gen_ids.py --check    # exit 1 if any C# file is out of date
Needs xlrd: python3 -m pip install -r tools/requirements-exporters.txt
"""
import argparse
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
from string_parser import StringExportError, parse_sheets, read_workbook  # noqa: E402

STRINGS_XLS = ROOT / 'Data' / 'Strings' / 'fortress_defender_strings.xls'
GAME_DATA = ROOT / 'Unity' / 'Assets' / 'StreamingAssets' / 'GameData'
SOUND_PACKS = ('audio_Music.pack', 'audio_SFX.pack')
OUT = ROOT / 'Unity' / 'Assets' / 'CastleFrenzy' / 'Scripts' / 'Autogenerated'


def string_ids(workbook):
    ids, _, warnings = parse_sheets(read_workbook(workbook))
    for warning in warnings:
        print('warning: ' + warning, file=sys.stderr)
    return ids


def sound_ids(game_data):
    names = []
    for pack in SOUND_PACKS:
        with zipfile.ZipFile(game_data / pack) as z:
            for info in z.infolist():
                if not info.is_dir():
                    names.append(Path(info.filename).stem.upper())
    if len(set(names)) != len(names):
        raise SystemExit('duplicate sound names in ' + ', '.join(SOUND_PACKS))
    return names


def render_strings(ids):
    body = ''.join(f'        public const int {k} = {v};\n' for v, k in enumerate(ids))
    sids = ''.join(f'            {{ "{k}", {v} }},\n' for v, k in enumerate(ids))
    return ('// Generated by tools/unity/gen_ids.py from Data/Strings/fortress_defender_strings.xls. Do not edit.\n'
            'using System.Collections.Generic;\n\nnamespace CastleFrenzy\n{\n'
            '    /// <summary>String table IDs (sheet_ROWID, in workbook order).</summary>\n'
            '    public static class STRING_IDS\n    {\n' + body +
            f'        public const int COUNT = {len(ids)};\n\n'
            '        public static readonly Dictionary<string, int> BySid = new Dictionary<string, int>\n        {\n'
            + sids + '        };\n    }\n}\n')


def render_sounds(names):
    body = ''.join(f'        public const int {k} = {v};\n' for v, k in enumerate(names))
    return ('// Generated by tools/unity/gen_ids.py from GameData/' + ' + '.join(SOUND_PACKS) + '. Do not edit.\n'
            '// Sound IDs: index of each file in the packs, in the order the game registers them.\n'
            'namespace CastleFrenzy\n{\n    public static partial class Ids\n    {\n' + body + '    }\n}\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--strings', type=Path, default=STRINGS_XLS, help='localization workbook (.xls)')
    ap.add_argument('--game-data', type=Path, default=GAME_DATA, help='folder with the audio_*.pack files')
    ap.add_argument('--out', type=Path, default=OUT, help='folder for the generated C# files')
    ap.add_argument('--check', action='store_true', help='only report out-of-date files (exit 1 if any)')
    a = ap.parse_args()

    try:
        outputs = {'StringIds.cs': render_strings(string_ids(a.strings)),
                   'Ids_sounds.cs': render_sounds(sound_ids(a.game_data))}
    except (OSError, StringExportError, zipfile.BadZipFile) as error:
        raise SystemExit(f'gen_ids: {error}')

    stale = []
    for name, text in outputs.items():
        target = a.out / name
        if target.is_file() and target.read_text(encoding='utf-8') == text:
            continue
        stale.append(name)
        if not a.check:
            a.out.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8')
    verb = 'out of date' if a.check else 'updated'
    print(f'{verb}: {", ".join(stale)}' if stale else 'ID tables are up to date')
    return 1 if a.check and stale else 0


if __name__ == '__main__':
    sys.exit(main())
