#!/usr/bin/env python3
"""Prepare Linux resources with AuroraMX sprites, Blender models and editable textures.

rebuild_Linux.sh supplies unchanged YAML copies with --sprite-exports.
Registered Blender exports arrive through --scene-exports. Other .bdae models
and string/config exports are reused. Source PNGs override legacy images.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from sprite_resources import copy_sprites, copy_headers, validate_assets
IMAGE_EXTENSIONS = {".png", ".tga", ".bmp"}
MANIFEST = "linux-resources.json"


def version():
    text = (ROOT / "config.bat").read_text()
    parts = []
    for name in ("MAJOR", "MINOR", "BUILD"):
        match = re.search(rf"^\s*set VERSION_{name}=(\d+)\s*$", text, re.MULTILINE | re.IGNORECASE)
        if not match:
            raise ValueError(f"Missing VERSION_{name} in config.bat")
        parts.append(match[1])
    return ".".join(parts)


def write_version():
    value = version()
    target = ROOT / "Src/Autogenerated/version.h"
    if not target.exists() or f'L"{value}"' not in target.read_text():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(f'#pragma once\nconst wchar_t g_castle_frenzy_version_str[] = L"{value}";\n')
    return value


def copy_exports(source, destination, extensions):
    for path in sorted(source.rglob("*")):
        if path.is_file() and path.suffix.lower() in extensions and ".svn" not in path.parts:
            target = destination / path.relative_to(source)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)


def source_image(relative, extension):
    candidates = [ROOT / "Data" / relative.with_suffix(extension)]
    if relative.parts[:2] == ("Sprites", "Fonts"):
        candidates.insert(0, ROOT / "Data/Fonts" / relative.name)
        candidates[0] = candidates[0].with_suffix(extension)
    return next((p for p in candidates if p.is_file()), None)


def png_image(path):
    from PIL import Image
    with Image.open(path) as image:
        return image.convert("RGBA")


def rebuild_audio(stage):
    names = []
    for group in ("Music", "SFX"):
        files = sorted((ROOT / "Data/Sounds" / group).rglob("*.wav"), key=lambda p: p.name.lower())
        if not files:
            raise ValueError(f"No source WAV files for {group}")
        if len({p.name.lower() for p in files}) != len(files):
            raise ValueError(f"Duplicate WAV filenames in {group}; sound packs use flat filenames")
        with zipfile.ZipFile(stage / f"audio_{group}.pack", "w", compression=zipfile.ZIP_STORED) as archive:
            for path in files:
                archive.write(path, path.name)
                names.append(path.stem.upper())
    # IDs follow Music then SFX, with each archive sorted by filename, as in
    # ListSoundFiles.exe and the engine's ZIP reader.
    ids = {name: i for i, name in enumerate(names)}
    target = ROOT / "Src/Autogenerated/sounds.h"
    old_ids = dict((name, int(value)) for name, value in re.findall(
        r"^#define\s+(\w+)\s+(\d+)\s*$", target.read_text(), re.MULTILINE))
    if old_ids != ids:
        target.write_text("// Generated by tools/linux/build_resources.py\n#pragma once\n\n" +
                          "".join(f"#define {name:<50} {i}\n" for name, i in ids.items()))
    print(f"Rebuilt sound packs: {len(names)} WAV files")


def build(output, sprite_exports=None, scene_exports=None):
    seed = ROOT / "Build/bin"
    output = output.resolve()
    if not output.is_relative_to(ROOT / "build"):
        raise ValueError("Resource output must be inside the project's lowercase build/ directory")
    if output.exists() and any(output.iterdir()) and not (output / MANIFEST).is_file():
        raise ValueError(f"Refusing to replace a directory without {MANIFEST}: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="linux-assets-", dir=output.parent) as temporary:
        stage = Path(temporary) / "assets"
        shutil.copytree(seed, stage, ignore=shutil.ignore_patterns(
            ".svn", "*.bak", "*.log", "*.LOG", "resources.pack", "*.sprite", "*.bsprite"))
        # Local saves are never part of a build; config/Profiles contains
        # checked-in templates and must be retained.
        for name in ("user_profile.xml", "default.xml"):
            (stage / name).unlink(missing_ok=True)
        copy_exports(ROOT / "Data/Sprites/bin", stage / "Sprites", IMAGE_EXTENSIONS)
        sprite_count = copy_sprites(ROOT / "Data/Sprites", stage / "Sprites", sprite_exports)
        if sprite_exports:
            copy_headers(sprite_exports, ROOT / "Src/Autogenerated")
        copy_exports(ROOT / "Data/Scenes/bin", stage / "Scenes", IMAGE_EXTENSIONS | {".bdae", ".ifl"})
        scene_files = set()
        model_assets = []
        if scene_exports:
            index = json.loads((scene_exports / "blender-models.json").read_text())
            if index.get("version") != 1 or index.get("exporter") != "Blender BDAE":
                raise ValueError("Invalid Blender export manifest")
            for relative, expected in index["files"].items():
                source = (scene_exports / relative).resolve()
                target = (stage / "Scenes" / relative).resolve()
                if not source.is_relative_to(scene_exports.resolve()) or not target.is_relative_to(stage / "Scenes"):
                    raise ValueError("Blender export path leaves the scene directory")
                if source.suffix.lower() not in {".bdae", ".png", ".tga"}:
                    raise ValueError("Unsupported Blender export file")
                if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
                    raise ValueError(f"Blender export changed after validation: {relative}")
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, target)
                scene_files.add(Path("Scenes") / relative)
            model_assets = index["assets"]
        for path in (ROOT / "Data/Fonts").glob("*.txt"):
            (stage / "Fonts").mkdir(exist_ok=True)
            shutil.copy2(path, stage / "Fonts" / path.name)
        copy_exports(ROOT / "Data/Effects", stage / "Effects", IMAGE_EXTENSIONS | {".xml"})
        for group, source in (("Sprites", ROOT / "Data/Sprites"),
                              ("Sprites/Fonts", ROOT / "Data/Fonts"),
                              ("Scenes", ROOT / "Data/Scenes")):
            for path in source.rglob("*.png"):
                if "bin" not in path.relative_to(source).parts:
                    target = stage / group / path.relative_to(source)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    if target.relative_to(stage) not in scene_files:
                        shutil.copy2(path, target)

        groups = {}
        for path in sorted(stage.rglob("*")):
            if path.suffix.lower() in IMAGE_EXTENSIONS:
                groups.setdefault(path.relative_to(stage).with_suffix(""), {})[path.suffix.lower()] = path
        converted = 0
        for relative, images in groups.items():
            # Fresh model exports take precedence over authoring textures.
            # Otherwise prefer editable PNG sources, retaining TGA/BMP imports.
            native = next((p for e, p in images.items() if relative.with_suffix(e) in scene_files), None)
            source = native or source_image(relative, ".png") or images.get(".png")
            if not source:
                source = source_image(relative, ".tga") or images.get(".tga") or images.get(".bmp")
            image = png_image(source)
            if relative.parts[0] == "Sprites":
                original = seed / relative.with_suffix(".png")
                if not original.is_file():
                    original = images.get(".tga") or images.get(".bmp") or images.get(".png")
                expected = png_image(original).size if original else image.size
                if image.size != expected:
                    raise ValueError(f"PNG atlas dimensions changed for {relative}; update its YAML module coordinates first")
            target = stage / relative.with_suffix(".png")
            image.save(target)
            for extension, old in images.items():
                if extension != ".png":
                    old.unlink()
            converted += 1
        rebuild_audio(stage)
        validate_assets(stage)
        manifest = {"version": version(), "texture_format": "png",
                    "sprite_format": "yaml", "yaml_sprites": sprite_count,
                    "sprite_exporter": "YAML copies (AuroraMX ID headers)" if sprite_exports else "YAML copies",
                    "model_exporter": "Blender BDAE" if scene_exports else "existing exports",
                    "blend_models": [{k: a[k] for k in ("blend", "output", "vertices", "triangles", "clips")} for a in model_assets],
                    "png_textures": converted, "files": sorted(str(p.relative_to(stage))
                    for p in stage.rglob("*") if p.is_file())}
        (stage / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n")
        if output.exists():
            shutil.rmtree(output)
        shutil.move(str(stage), output)
    print(f"Resources ready: {output} ({len(manifest['files'])} files, {converted} PNG textures)")
    print(f"Sprites: {sprite_count} unchanged YAML copies; "
          f"models: {len(model_assets)} Blender export(s), other models from existing exports; "
          "reused string/config exports; rebuilt textures and sound packs.")


def package(output, binary):
    manifest = json.loads((output / MANIFEST).read_text())
    if manifest["texture_format"] != "png":
        raise ValueError("Resources must use PNG textures; rebuild resources first")
    if manifest.get("sprite_format") != "yaml":
        raise ValueError("Sprite format differs from YAML; rebuild resources before packaging")
    validate_assets(output)
    name = f"CastleFrenzy_Linux_v{version()}_png"
    destination = ROOT / "build/packages" / (name + ".zip")
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(".zip.tmp")
    with zipfile.ZipFile(temporary, "w", zipfile.ZIP_DEFLATED, compresslevel=1) as archive:
        archive.write(binary, f"{name}/bin/FortressDefender")
        archive.write(ROOT / "Lib/yaml-cpp.LICENSE", f"{name}/licenses/yaml-cpp.txt")
        for path in sorted(output.rglob("*")):
            if path.is_file():
                archive.write(path, f"{name}/assets/{path.relative_to(output)}")
        launcher = zipfile.ZipInfo(f"{name}/run.sh")
        launcher.external_attr = 0o100755 << 16
        archive.writestr(launcher, '#!/usr/bin/env bash\nset -euo pipefail\n'
                         'game_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)\n'
                         'exec "$game_dir/bin/FortressDefender" --assets "$game_dir/assets" "$@"\n')
        archive.writestr(f"{name}/README.txt", "Run ./run.sh from a graphical Linux desktop.\n"
                         "This is a 64-bit build; install the runtime dependencies in the project readme.\n"
                         "Builds using the rootless .deps bootstrap retain absolute library paths\n"
                         "to the project directory and require those dependencies at that location.\n"
                         "For distribution to other machines, build with system-installed dependencies.\n")
    temporary.replace(destination)
    print(f"Package ready: {destination}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", action="store_true", help="update version.h from config.bat and print version")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--sprite-exports", type=Path, help="AuroraMX batch bin/ with unchanged YAML copies and ID headers")
    parser.add_argument("--scene-exports", type=Path, help="Validated Blender model export directory")
    parser.add_argument("--package", type=Path, metavar="EXECUTABLE")
    args = parser.parse_args()
    if args.version:
        print(write_version())
    elif not args.output:
        parser.error("--output is required")
    elif args.package:
        package(args.output, args.package)
    else:
        build(args.output, args.sprite_exports, args.scene_exports)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        print(f"Resource build failed: {error}", file=sys.stderr)
        sys.exit(1)
