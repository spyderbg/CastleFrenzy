"""Run: python tools/test_string_parser.py

Requires tools/requirements-strings.txt. No Java installation is needed.
"""
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
import unittest

import string_parser as exporter

ROOT = Path(__file__).resolve().parents[1]
WORKBOOK = ROOT / "Data/Strings/fortress_defender_strings.xls"


class StringParserTests(unittest.TestCase):
    def test_excel_punctuation_quotes_and_java_trim(self):
        self.assertEqual(exporter.format_cell('  \u201cIt\u2019s ready\u2026\u201d\r\n'), "It's ready...")
        self.assertEqual(exporter.format_cell('""'), '""')
        self.assertEqual(exporter.format_cell('\u00a0Text\u00a0'), '\u00a0Text\u00a0')

    def test_utf16_offsets_cover_empty_cjk_and_non_bmp_strings(self):
        strings = ["", "caf\u00e9", "\u65e5\u672c\u8a9e", "\U0001f600", "line\nnext"]
        data = exporter.encode_table(strings)
        count, *offsets = struct.unpack_from(f"<{len(strings) + 1}I", data)
        self.assertEqual(count, len(strings))
        self.assertEqual(offsets[0], 4 + 4 * count)
        for i, start in enumerate(offsets):
            end = offsets[i + 1] if i + 1 < count else len(data)
            self.assertEqual(data[start:end].decode("utf-16-le"), strings[i] + "\0")

    def test_font_mapping_sorts_unique_characters_and_excludes_controls(self):
        self.assertEqual(exporter.font_mapping(["bbAA \n\t", "\u65e5\u65e5"]),
                         b"\xff\xfe" + " Ab\u65e5".encode("utf-16-le"))

    def test_missing_and_new_languages_stay_aligned_with_ids(self):
        ids, languages, warnings = exporter.parse_sheets([
            ("Menu", [["::ID::", "EN", "FR"], ["one", "One", "Un"],
                      ["", "ignored", "ignored"], ["two", "Two", "Deux"]]),
            ("Help", [["::ID::", "FR", "", "JP"], ["three", "Trois", "", "\u4e09"]]),
        ], language_count=2)
        self.assertEqual(ids, ["MENU_ONE", "MENU_TWO", "HELP_THREE"])
        self.assertEqual(languages, {"EN": ["One", "Two", ""],
                                    "FR": ["Un", "Deux", "Trois"],
                                    "JP": ["", "", "\u4e09"]})
        self.assertEqual(warnings, [])

    def test_escaped_newlines_and_language_count_warning(self):
        _, languages, warnings = exporter.parse_sheets([
            ("Menu", [["::ID::", "EN"], ["one", "one\\ntwo"]])
        ], language_count=7)
        self.assertEqual(languages["EN"], ["one\ntwo"])
        self.assertIn("expected 7 languages, found 1", warnings[0])

    def test_invalid_workbooks_and_names_are_rejected(self):
        cases = [
            ([("Menu", [["ID", "EN"], ["one", "One"]])], "Missing ::ID::"),
            ([("Menu", [["::ID::", "EN", "EN"], ["one", "One", "One"]])], "Duplicate language"),
            ([("Menu", [["::ID::", "../EN"], ["one", "One"]])], "Invalid language"),
            ([("Menu", [["::ID::", "EN"], ["one", "One"], ["ONE", "Two"]])], "Duplicate string ID"),
            ([("Menu", [["::ID::"], ["one"]])], "No language columns"),
            ([], "no string IDs"),
        ]
        for sheets, message in cases:
            with self.subTest(message=message), self.assertRaisesRegex(exporter.StringExportError, message):
                exporter.parse_sheets(sheets)

    def test_project_workbook_matches_all_shipped_tables_maps_and_headers(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary)
            count, languages = exporter.export_strings(WORKBOOK, output)
            self.assertEqual(count, 509)
            self.assertEqual(languages, ("EN", "FR", "ES", "DE", "IT", "JP", "SC"))
            self.assertEqual(len(list(output.iterdir())), 17)
            for path in output.iterdir():
                if path.suffix == ".txt":
                    reference = ROOT / "Build/bin/Strings" / path.name
                elif path.suffix == ".hpp":
                    reference = ROOT / "Src/Autogenerated" / path.name
                else:
                    continue
                self.assertEqual(path.read_bytes(), reference.read_bytes(), path.name)

    def test_repeated_exports_do_not_append_gen_or_rewrite_unchanged_files(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary)
            exporter.export_strings(WORKBOOK, output)
            previous = {p.name: (p.read_bytes(), p.stat().st_mtime_ns) for p in output.iterdir()}
            exporter.export_strings(WORKBOOK, output)
            self.assertEqual(previous, {p.name: (p.read_bytes(), p.stat().st_mtime_ns) for p in output.iterdir()})

    def test_invalid_input_preserves_existing_exports(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output = root / "out"
            exporter.export_strings(WORKBOOK, output)
            before = {p.name: p.read_bytes() for p in output.iterdir()}
            invalid = root / "bad.xls"
            invalid.write_bytes(b"not an Excel workbook")
            with self.assertRaises(exporter.StringExportError):
                exporter.export_strings(invalid, output)
            self.assertEqual(before, {p.name: p.read_bytes() for p in output.iterdir()})

    def test_cli_handles_spaces_and_reports_missing_input(self):
        with tempfile.TemporaryDirectory(prefix="string export ") as temporary:
            root = Path(temporary)
            result = subprocess.run([sys.executable, str(ROOT / "tools/string_parser.py"),
                                     str(WORKBOOK), str(root / "output with spaces"), "7"],
                                    capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn("509 strings in 7 languages", result.stdout)
            result = subprocess.run([sys.executable, str(ROOT / "tools/string_parser.py"),
                                     str(root / "missing.xls"), str(root / "bad output")],
                                    capture_output=True, text=True)
            self.assertEqual(result.returncode, 1)
            self.assertIn("String export failed:", result.stderr)
            self.assertFalse((root / "bad output").exists())


if __name__ == "__main__":
    unittest.main()
