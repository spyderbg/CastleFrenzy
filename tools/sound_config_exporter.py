#!/usr/bin/env python3
"""Export SoundConfiguration.xls to the game's sound-configuration XML.

Usage: python tools/sound_config_exporter.py input.xls output.xml
Install dependencies with: python -m pip install -r tools/requirements-exporters.txt

The legacy XML is a sequence of soundsconfig elements, with one global default
followed by each sfx_ row. Empty attributes inherit the global settings.
"""
from __future__ import annotations

import argparse
from html import escape
import math
import os
from pathlib import Path
import stat
import sys
import tempfile

from string_parser import format_cell

SHEET_NAME = "Sound Design Document"
GLOBAL_ID = "Global_SoundConfig"
ATTRIBUTES = ((3, "int", "Obligatory", "0"), (4, "int", "Overlap", "2"),
              (5, "int", "Priority", "3"), (6, "float", "Volume", "1"))


class SoundConfigExportError(ValueError):
    """Invalid sound workbook or missing XLS dependency."""


def read_sound_rows(filename: Path):
    try:
        import xlrd
    except ImportError as error:
        raise SoundConfigExportError(
            "Reading .xls requires xlrd. Install it with: "
            "python -m pip install -r tools/requirements-exporters.txt"
        ) from error
    try:
        book = xlrd.open_workbook(str(filename))
    except xlrd.XLRDError as error:
        raise SoundConfigExportError(str(error)) from error
    try:
        if SHEET_NAME not in book.sheet_names():
            raise SoundConfigExportError(f"Missing {SHEET_NAME!r} worksheet")
        sheet = book.sheet_by_name(SHEET_NAME)
        if sheet.ncols < 7:
            raise SoundConfigExportError(f"{SHEET_NAME}: expected at least seven columns")

        def cell_text(row, column):
            cell = sheet.cell(row, column)
            if cell.ctype in (xlrd.XL_CELL_EMPTY, xlrd.XL_CELL_BLANK):
                return ""
            if cell.ctype == xlrd.XL_CELL_TEXT:
                return format_cell(cell.value)
            if cell.ctype == xlrd.XL_CELL_NUMBER and math.isfinite(cell.value):
                # JExcel's General number format is #.###, without grouping.
                return format(cell.value, ".3f").rstrip("0").rstrip(".")
            if cell.ctype == xlrd.XL_CELL_BOOLEAN:
                return "true" if cell.value else "false"
            raise SoundConfigExportError(
                f"{SHEET_NAME}, row {row + 1}, column {column + 1}: expected text or a finite number"
            )

        rows = []
        for row in range(sheet.nrows):
            if sheet.cell(row, 0).ctype != xlrd.XL_CELL_TEXT:
                continue
            name = cell_text(row, 0)
            if not name.startswith("sfx_"):
                continue
            values = [name, "", ""]
            values.extend(cell_text(row, column) for column in range(3, 7))
            rows.append(values)
        return rows
    finally:
        book.release_resources()


def render_config(rows):
    parts = ['<?xml version="1.0"?>\n\n<!--This file is autogenerated-->\n\n']

    def attribute(kind, name, value):
        return f'\t<{kind} name="{name}" value="{escape(value, quote=True)}" />\n'

    parts.append(f'<soundsconfig id="{GLOBAL_ID}">\n')
    parts.extend(attribute(kind, name, default) for _, kind, name, default in ATTRIBUTES)
    parts.append('</soundsconfig>\n\n')
    seen = set()
    for row in rows:
        if not row or not row[0].startswith("sfx_"):
            continue
        if len(row) < 7:
            raise SoundConfigExportError(f"{row[0]}: expected seven columns")
        identifier = row[0] + ".wav"
        if identifier in seen:
            raise SoundConfigExportError(f"Duplicate sound ID {identifier}")
        seen.add(identifier)
        parts.append(f'<soundsconfig id="{escape(identifier, quote=True)}" extends="{GLOBAL_ID}">\n')
        for column, kind, name, _ in ATTRIBUTES:
            value = ("1" if row[column] == "Yes" else "0") if column == 3 else row[column]
            if not value:
                continue
            try:
                if kind == "int":
                    int(value)
                elif not math.isfinite(float(value)):
                    raise ValueError("not finite")
            except ValueError as error:
                raise SoundConfigExportError(f"{identifier}: invalid {name} value {value!r}") from error
            parts.append(attribute(kind, name, value))
        parts.append('</soundsconfig>\n\n')
    return "".join(parts).encode("utf-8")


def export_sound_config(filename: Path, output: Path):
    rows = read_sound_rows(Path(filename))
    data = render_config(rows)
    output = Path(output)
    if output.is_file() and output.read_bytes() == data:
        return len(rows)
    output.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(output.stat().st_mode) if output.exists() else 0o644
    descriptor, temporary = tempfile.mkstemp(prefix=output.name + ".", dir=output.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
        os.chmod(temporary, mode)
        os.replace(temporary, output)
    finally:
        Path(temporary).unlink(missing_ok=True)
    return len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("workbook", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        count = export_sound_config(args.workbook, args.output)
    except (OSError, SoundConfigExportError, UnicodeError) as error:
        parser.exit(1, f"Sound export failed: {error}\n")
    print(f"Exported {count} sound configurations to {args.output}")


if __name__ == "__main__":
    main()
