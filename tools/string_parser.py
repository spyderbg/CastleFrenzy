#!/usr/bin/env python3
"""Export the localization XLS workbook without Java.

Usage: python tools/string_parser.py input.xls output_directory 7
Install the XLS reader with: python -m pip install -r tools/requirements-exporters.txt

The game tables contain a little-endian uint32 count and byte offsets followed
by NUL-terminated UTF-16LE strings. Font maps and the combined .gen use UTF-16LE
with a BOM. The two ID headers retain the legacy Windows-1252 layout.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import stat
import struct
import sys
import tempfile

PREFIX = "FortressDefender_"
JAVA_WHITESPACE = "".join(chr(i) for i in range(33))
EXCEL_PUNCTUATION = str.maketrans({"\u201c": '"', "\u201d": '"', "\u2019": "'", "\u2026": "..."})
HEADER = ("///////////////////////////////////////////////////////////\n"
          "// WARNING: This file was generated by 'StringParser' tool!\n"
          "///////////////////////////////////////////////////////////\n\n\nBEGIN_STRINGS\n\n")
FOOTER = "\nEND_STRINGS\n///////////////////////////////////////////////////////////\n\n"


class StringExportError(ValueError):
    """Invalid localization workbook or missing XLS dependency."""


def format_cell(value: str) -> str:
    """Match Java's punctuation cleanup, ASCII trim and outer-quote removal."""
    value = value.translate(EXCEL_PUNCTUATION).strip(JAVA_WHITESPACE)
    if len(value) > 2 and value.startswith('"') and value.endswith('"'):
        value = value[1:-1]
    return value


def read_workbook(filename: Path):
    try:
        import xlrd
    except ImportError as error:
        raise StringExportError(
            "Reading .xls requires xlrd. Install it with: "
            "python -m pip install -r tools/requirements-exporters.txt"
        ) from error
    try:
        book = xlrd.open_workbook(str(filename))
    except xlrd.XLRDError as error:
        raise StringExportError(str(error)) from error
    try:
        sheets = []
        for sheet in book.sheets():
            rows = []
            for row_index, row in enumerate(sheet.get_rows(), 1):
                values = []
                for column, cell in enumerate(row, 1):
                    if cell.ctype in (xlrd.XL_CELL_EMPTY, xlrd.XL_CELL_BLANK):
                        value = ""
                    elif cell.ctype == xlrd.XL_CELL_TEXT:
                        value = cell.value
                    elif cell.ctype == xlrd.XL_CELL_BOOLEAN:
                        value = "true" if cell.value else "false"
                    else:
                        # Localization cells must be text: interpreting numeric
                        # formats/dates differently from Excel can corrupt a label.
                        raise StringExportError(
                            f"{sheet.name}, row {row_index}, column {column}: "
                            "non-text cell; store string IDs and translations as text"
                        )
                    values.append(format_cell(value))
                rows.append(values)
            sheets.append((sheet.name, rows))
        return sheets
    finally:
        book.release_resources()


def parse_sheets(sheets, language_count=7):
    """Keep IDs in workbook order and align every language to those IDs."""
    if language_count < 1:
        raise StringExportError("The expected language count must be positive")
    ids, languages, warnings = [], {}, []
    seen_ids = set()
    for name, rows in sheets:
        if not rows or not rows[0] or rows[0][0] != "::ID::":
            raise StringExportError(f"Missing ::ID:: column in {name}")
        columns = {}
        for index, language in enumerate(rows[0][1:], 1):
            if not language:
                continue
            if language in columns:
                raise StringExportError(f"Duplicate language {language!r} in {name}")
            if Path(language).name != language or any(c in language for c in '/\\\0:*?"<>|') or language in {'.', '..'}:
                raise StringExportError(f"Invalid language name {language!r} in {name}")
            columns[language] = index
            languages.setdefault(language, [""] * len(ids))
        if not columns:
            raise StringExportError(f"No language columns in {name}")
        if len(columns) != language_count:
            warnings.append(f"{name}: expected {language_count} languages, found {len(columns)}")
        for row in rows[1:]:
            if not row or not row[0]:
                continue
            identifier = f"{name}_{row[0]}".upper()
            if identifier in seen_ids:
                raise StringExportError(f"Duplicate string ID {identifier}")
            seen_ids.add(identifier)
            ids.append(identifier)
            for language, strings in languages.items():
                column = columns.get(language)
                text = row[column] if column is not None and column < len(row) else ""
                strings.append(text.replace("\\n", "\n"))
    if not ids:
        raise StringExportError("The workbook contains no string IDs")
    return ids, languages, warnings


def _java_language_order(names):
    """Retain Hashtable enumeration order for the combined legacy font input."""
    def hash_code(name):
        encoded = name.encode("utf-16-be")
        value = 0
        for (unit,) in struct.iter_unpack(">H", encoded):
            value = (31 * value + unit) & 0xffffffff
        return value & 0x7fffffff

    buckets = [[] for _ in range(11)]
    for count, name in enumerate(names):
        if count >= int(len(buckets) * 0.75):
            previous = buckets
            buckets = [[] for _ in range(2 * len(previous) + 1)]
            for bucket in reversed(previous):
                for old in bucket:
                    buckets[hash_code(old) % len(buckets)].insert(0, old)
        buckets[hash_code(name) % len(buckets)].insert(0, name)
    return [name for bucket in reversed(buckets) for name in bucket]


def encode_table(strings):
    payloads = [(text + "\0").encode("utf-16-le") for text in strings]
    offset = 4 + 4 * len(payloads)
    offsets = []
    for payload in payloads:
        offsets.append(offset)
        offset += len(payload)
    return struct.pack(f"<{len(offsets) + 1}I", len(payloads), *offsets) + b"".join(payloads)


def font_mapping(strings):
    units = {unit for text in strings for (unit,) in struct.iter_unpack("<H", text.encode("utf-16-le")) if unit >= 32}
    return b"\xff\xfe" + b"".join(struct.pack("<H", unit) for unit in sorted(units))


def render_outputs(ids, languages):
    outputs = {}
    for suffix, macro, quote in [("", "STRING_", ""), ("_string", "S_STRING_", '"')]:
        body = "".join(f"{macro}( {i},\t{quote}{identifier}{quote} );\n" for i, identifier in enumerate(ids))
        outputs[f"{PREFIX}ID{suffix}.hpp"] = (HEADER + body + FOOTER).encode("cp1252", errors="replace")
    combined = []
    for language in _java_language_order(languages):
        strings = languages[language]
        outputs[f"{PREFIX}{language}.txt"] = encode_table(strings)
        outputs[f"FontMapping_{language}.txt"] = font_mapping(strings)
        combined.append(b"\xff\xfe" + "".join(text + "\0" for text in strings).encode("utf-16-le"))
    outputs[f"{PREFIX}All_Strings.gen"] = b"".join(combined)
    return outputs


def export_strings(filename: Path, output: Path, language_count=7):
    ids, languages, warnings = parse_sheets(read_workbook(Path(filename)), language_count)
    outputs = render_outputs(ids, languages)
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    for name, data in outputs.items():
        target = output / name
        if target.is_file() and target.read_bytes() == data:
            continue
        mode = stat.S_IMODE(target.stat().st_mode) if target.exists() else 0o644
        descriptor, temporary = tempfile.mkstemp(prefix=name + ".", dir=output)
        try:
            with os.fdopen(descriptor, "wb") as stream:
                stream.write(data)
            os.chmod(temporary, mode)
            os.replace(temporary, target)
        finally:
            Path(temporary).unlink(missing_ok=True)
    for warning in warnings:
        print(f"Warning: {warning}", file=sys.stderr)
    return len(ids), tuple(languages)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("workbook", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("languages", type=int, nargs="?", default=7, help="expected language columns per sheet (default: 7)")
    args = parser.parse_args()
    try:
        count, languages = export_strings(args.workbook, args.output, args.languages)
    except (OSError, StringExportError, UnicodeError, struct.error) as error:
        parser.exit(1, f"String export failed: {error}\n")
    print(f"Exported {count} strings in {len(languages)} languages ({', '.join(languages)}) to {args.output}")


if __name__ == "__main__":
    main()
