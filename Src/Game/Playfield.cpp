template <typename T>
T RandElement (const array<T>& arr)
{
	return arr[RandInt(0, arr.size() - 1)];
}

int RandomEnemyCountByDifficulty (GameDifficulty difficulty, int min, int max)
{
	switch (difficulty)
	{
	case GD_Easy:   return RandInt(min, (2 * min + 4 * max + 3) / 6);
	case GD_Normal: return RandInt((4 * min + 2 * max + 3) / 6, (2 * min + 4 * max + 3) / 6);
	case GD_Hard:   return RandInt((2 * min + 4 * max + 3) / 6, max);
	default:		return RandInt(min, max);
	}
}

void CPlayfield::loadWaves ()
{
	for (int i = 0; i < 8; ++i)
		m_unitsInLane[i] = 0;

	m_waves.clear();
	m_extraSpawns.clear();

	m_dayTextTime = 0.0f;

	CProjectile::reset();

	GX_ASSERT(m_CurrentLevel >= 0);
	GX_ASSERT(m_CurrentDay >= 0);

	array<int> daysPerLevel = getNumberOfDaysPerLevel();
	bool isEndless = m_CurrentLevel == daysPerLevel.size() - 1;

	Day* level = 0;
	if (isEndless)
	{
		DBG_OUT("Loading endless day %d\n", m_CurrentDay);

		array<Day*> segmentsByDifficulty[3];
		for (int i = 0; i < daysPerLevel[daysPerLevel.size() - 1]; ++i)
		{
			Day* level = loadDayInfo(getDayPath(m_CurrentLevel, i).c_str());
			segmentsByDifficulty[level->difficulty].push_back(level);
		}

		int dayMaxTime = 90;
		array<float> odds = getEndlessOdds(m_CurrentDay);
		float totalOdds = odds[0] + odds[1] + odds[2];

		DBG_OUT("  chances: easy %3.1f%%, medium %3.1f%%, hard %3.1f%%\n",
			100.0f * odds[0] / totalOdds, 100.0f * odds[1] / totalOdds, 100.0f * odds[2] / totalOdds);

		level = new Day;
		level->challenge = CT_None;
		level->difficulty = 0;
		level->dayEndTime = 0;
		const char* difficulties[] = { "easy", "medium", "hard" };
		while (level->dayEndTime < dayMaxTime)
		{
			float r = RandFloat(0.0f, totalOdds);
			int difficulty = r < odds[0] ? 0 : r < odds[0] + odds[1] ? 1 : 2;
			int levelToLoad = RandInt(0, segmentsByDifficulty[difficulty].size() - 1);
			DBG_OUT("  %s %d\n", difficulties[difficulty], levelToLoad + 1);
			level->dayEndTime = appendDayToDay(level, level->dayEndTime, segmentsByDifficulty[difficulty][levelToLoad]);
		}
	}
	else
	{
		level = loadDayInfo(getDayPath(m_CurrentLevel, m_CurrentDay).c_str());
	}
	
	if (level)
	{
		m_challenge.setType(level->challenge);
		for (int i = 0; i < level->waves.size(); ++i)
		{
			Wave* wave = level->waves[i];
			if (wave->variants.size() == 0)
				continue;
			float time = 0.0f;
			for (int rep = 0; rep < wave->repeatCount && time < level->dayEndTime; ++rep)
			{
				int timeStart = wave->timeStart + wave->repeatInterval * rep;
				Variant* var = RandElement(wave->variants);
				time = RandFloat(timeStart, timeStart + wave->timeInterval);
				for (int j = 0; j < var->enemyTypes.size(); ++j)
				{
					EnemyType* enemy = var->enemyTypes[j];
					int count = RandomEnemyCountByDifficulty(getDifficulty(), enemy->minCount, enemy->maxCount);
					if (g_unitTypes[enemy->unitType]->attributes->existsAttribute("MindControl"))
					{
						// spawn just one unit with appropriate number of slaves
						SUnitAtTime unit;
						unit.type = enemy->unitType;
						unit.time = time;
						unit.slaves = count;
						unit.riders = 0;
						unit.intro = var->intro;
						m_waves.push_back(unit);
					}
					else
					{
						for (int k = 0; k < count; ++k)
						{
							SUnitAtTime unit;
							unit.type = enemy->unitType;
							unit.time = wave->packed ? time : (timeStart + k * wave->timeInterval / float(count));
							unit.slaves = 0;
							unit.riders = g_unitTypes[enemy->unitType]->attributes->existsAttribute("Rider");
							unit.intro = var->intro;
							m_waves.push_back(unit);
						}
					}
				}
			}
		}
		m_waves.sort();
		delete level;
	}

	m_MaxUnits = m_waves.size();
}

