const int RTT_W = 512;
const int RTT_H = 512;

void CPlayfield::prerenderBackground()
{
	if (CGameConfig::DisableRTT) return;

	IVideoDriver* driver = __IRR_DRIVER();
	ISceneManager* smgr = __IRR_SCENE();

	if (!m_prerenderedTexture)
	{
		m_prerenderedTexture = driver->createRenderTargetTexture(d2i(RTT_W, RTT_H));
	}

	ITimelineController * cameraControl = m_cameraScene->getAnimators().getFirstElem()->getTimelineCtrl();
	cameraControl->setClip("sceneloop");
	cameraControl->setLoop(false);

	smgr->update(1);

	hideForeground();
	showBackground();

	SColorf ambient = GetSunLight()->getLightData().AmbientColor;
	GetSunLight()->getLightData().AmbientColor = SColorf(1,1,1,1);
	r2i vp = driver->getViewPort();

	driver->setRenderTarget(m_prerenderedTexture);
#if defined(OS_WIN32) || defined(OS_LINUX)
	driver->setViewPort(r2i(0, 0, 480, 320));
#else
	driver->setViewPort(r2i(0, 0, 320, 480));
#endif

	ICameraSceneNode *activeCamera = smgr->getActiveCamera();

	matrix4 projection = activeCamera->getProjectionMatrix();
	// remember old projection to be restored later
	matrix4 back_projection = projection;
	
	//return orientation to normal
	switch ( driver->getOrientation3D() )
	{
	case irr::video::EOO_0 : 
		break;
	case irr::video::EOO_90:
		break;
	case irr::video::EOO_180:
		projection[0] = -projection[0];
		projection[4] = -projection[4];
		projection[8] = -projection[8];
		projection[12] = -projection[12];

		projection[1] = -projection[1];
		projection[5] = -projection[5];
		projection[9] = -projection[9];
		projection[13] = -projection[13];
		break;
	case irr::video::EOO_270:
		projection[0] = -projection[0];
		projection[4] = -projection[4];
		projection[8] = -projection[8];
		projection[12] = -projection[12];

		projection[1] = -projection[1];
		projection[5] = -projection[5];
		projection[9] = -projection[9];
		projection[13] = -projection[13];
		break;
	}

	activeCamera->setProjectionMatrix( projection );
	
	smgr->drawAll();
	
	activeCamera->setProjectionMatrix( back_projection );

	GetSunLight()->getLightData().AmbientColor = ambient;
	driver->setRenderTarget(0, 0);
	driver->setViewPort(vp);
}

