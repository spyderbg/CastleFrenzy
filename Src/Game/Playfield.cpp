void CPlayfield::fadeIn(f32 duration)
{
	m_hudAlpha = 0.0f;
	if (duration == 0)
	{
		m_fadeAlpha = 0;
		m_fadeDir = 0;
	}
	else
	{
		m_fadeAlpha = 255;
		m_fadeDuration = duration;
		m_fadeTimer = 0;
		m_fadeDir = -1;
	}
}

void CPlayfield::fadeOut(f32 duration)
{
	if (duration == 0)
	{
		m_fadeAlpha = 255;
		m_fadeDir = 0;
	}
	else
	{
		m_fadeAlpha = 0;
		m_fadeDuration = duration;
		m_fadeTimer = 0;
		m_fadeDir = +1;
	}
}

void CPlayfield::UpdateFade(f32 time)
{
	if (m_fadeDir != 0)
	{
		m_fadeAlpha = 255 * m_fadeTimer / m_fadeDuration;
		CLAMP(m_fadeAlpha, 0, 255);
		if (m_fadeDir < 0)
			m_fadeAlpha = 255 - m_fadeAlpha;

		if (m_fadeTimer >= m_fadeDuration)
			m_fadeDir = 0;

		m_fadeTimer += time;
	}
}

void CPlayfield::DrawFade()
{
	if (m_fadeAlpha > 0)
	{
		__IRR_DRIVER()->draw2DRectangle(SColor(m_fadeAlpha,0,0,0), r2i(0, 0, 480, 320));
	}
}

