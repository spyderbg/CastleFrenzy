int CPlayfield::findFreeLane ()
{
	int bestLanes[8] = { 0 };
	int bestLanesCount = 0;
	int bestLanesValue = 0;

	for (int i = 0; i < 8; ++i)
	{
		if (m_unitsInLane[i] == 0)
		{
			int j;
			for (j = 1; j < 8; ++j)
			{
				if (i - j >= 0 && m_unitsInLane[i - j] > 0)
					break;

				if (i + j < 8 && m_unitsInLane[i + j] > 0)
					break;
			}

			if (j > bestLanesValue)
			{
				bestLanesCount = 0;
				bestLanesValue = j;
			}

			if (j == bestLanesValue)
			{
				bestLanes[bestLanesCount++] = i;
			}			
		}
	}

	return bestLanes[RandInt(0, bestLanesCount - 1)];
}

