void CPlayfield::SetLevelScores (Menu_Ingame* menu)
{
	int gold  = m_levelStats.Gold  + m_gold;
	int souls = m_levelStats.Souls + m_souls;

	for (int i = 0; i < WT_Count; ++i)
	{
		if (m_levelStats.WeaponLevel[i] != WL_None)
		{
			gold += GetWeaponInfo((EWeaponType)i, m_levelStats.WeaponLevel[i]).getPriceGold();
			souls += GetWeaponInfo((EWeaponType)i, m_levelStats.WeaponLevel[i]).getPriceSouls();
		}
	}

	menu->SetLevelScores(gold, souls, getDifficulty());
}
