void CPlayfield::StartNewLevel( s32 level )
{
	m_damage = 0.0f;

	m_CurrentLevel = level;
	m_CurrentDay = 0;
	m_nextCutscene = CS_Intro;

	m_kills = 0;

	CLevelStats & stats = GetLevelStats();
	stats.reset();

	Level* levelinfo = loadLevelInfo(getLevelPath(level).c_str());

	stats.SpellAvailable = levelinfo->spellAvailableInShop;
	if (CGameConfig::AllWeaponsSold)
	{
		for (int i = 0; i < WT_Count; i++)
		{
			if (i == WT_Spell)
				stats.WeaponLevel[i] = ST_Tornado;
			else
				stats.WeaponLevel[i] = WL_3;
		}
	}
	else
	{
		for (int i = 0; i < WT_Count; i++)
		{
			if (i == WT_Spell)
			{
				stats.WeaponLevel[i] = levelinfo->spellBought ? stats.SpellAvailable : ST_None;
				stats.WeaponAvailable[i] = (stats.SpellAvailable != ST_None);
			}
			else
			{
				stats.WeaponLevel[i] = levelinfo->weaponStartingLevel[i];
				stats.WeaponAvailable[i] = levelinfo->weaponAvailableInShop[i];
			}
		}
	}

	delete levelinfo;

	++m_gameNumber;

	WriteProfileStats();

	if( !m_isEndless )
	{
		/// Reset achievement 'Cash & Carry'
		__ACHIEVEMENTS()->setValue( "Cash & Carry", 0 );
	}

	__MGR_STATES()->switchState<GSLevel>();

#ifdef OS_IPHONE
	if (m_CurrentLevel == 0)
	{
		char path[512] = { 0 };
		strcat(path, __APP()->getFileResPath());
		strcat(path, "intro_2500.mp4");
		MP_playMovie(path);
	}
#endif
}

