void CPlayfield::updateEffects()
{
	for (int i = 0; i < m_effects.size(); ++i)
	{
		if (m_effects[i].inst->IsAnimEnded())
		{
			delete m_effects[i].inst;
			m_effects.erase(i);
			--i;
			continue;
		}

		m_effects[i].inst->Update(_time);
	}

	for (int i = 0; i < m_flyingMoney.size(); ++i)
	{
		if (m_flyingMoney[i].time <= 0.0f)
		{
			m_flyingMoney.erase(i);
			--i;
			continue;
		}
		
		m_flyingMoney[i].time -= _time;
		m_flyingMoney[i].position += vector2df(0, -20) * _time;
	}

	for (int i = 0; i < m_flyingSouls.size(); i++)
	{
		if (m_flyingSouls[i].time >= m_flyingSouls[i].duration)
		{
			m_souls += m_flyingSouls[i].amount;

			delete m_flyingSouls[i].inst;
			m_flyingSouls.erase(i);
			--i;
			continue;
		}

		m_flyingSouls[i].time += _time;
		m_flyingSouls[i].inst->Update(_time);
	}
}

void CPlayfield::calc3D()
{
	ISceneNode * node;
	
	node = __IRR_SCENE()->getSceneNodeFromName("d_path_start", m_castle);
	m_path.start = node->getPosition();

	node = __IRR_SCENE()->getSceneNodeFromName("d_path_end", m_castle);
	m_path.end = node->getPosition();

	vector3df dir = m_path.getVector();
	vector3df up = vector3df(0, 1, 0);
	vector3df right = dir.crossProduct(up).normalize();
	vector3df middle = m_path.start.getInterpolated(m_path.end, 0.74f);

	m_groundPlane.setPlane(m_path.start, m_path.end, m_path.end - right);
	m_flyingPlane.setPlane(m_path.start, m_path.end, m_path.end + up);
	m_castlePlane.setPlane(m_path.end, m_path.end + right, m_path.end + up);
	m_outOfScreenPlane.setPlane(middle, middle + up, middle + right);
}

