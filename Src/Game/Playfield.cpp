void CPlayfield::updateTouch()
{
	bool first = m_touch->m_assignedTouchIndex != -1;
	bool second = m_touch->m_assignedTouchIndex2 != -1;
	
	m_isNowActivated =	(first && !m_firstTouch) || (second && !m_secondTouch);
	m_isNowReleased =	(!first && m_firstTouch) || (!second && m_secondTouch);

	if( !first && !second )
	{
		m_touch->m_useFirstTouchForDefault = true;
	}
	else
	{
		bool inUse = m_unitDragged || m_spell->isCasting();

		if( !inUse && first && (second && !m_secondTouch) )
		{
			m_touch->m_useFirstTouchForDefault = false;
		}
	}
			
	//DBG_OUT( "updateTouch()\tfirst=%d second=%d check=%d\n", (s32)first, (s32)second, (s32)useFirst );
	
	m_firstTouch	= first;
	m_secondTouch	= second;
}

void CPlayfield::reassignTouchTo(CTouchElement* touch)
{
	m_touch->ReassignTouchTo(touch);
	m_isNowActivated = false;
	m_isNowReleased = false;
	m_firstTouch = false;
	m_secondTouch = false;
}

