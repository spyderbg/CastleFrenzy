void CPlayfield::ResetLevel()
{
	/// Remove all units
	TUnitList::Iterator it = m_units.begin();
	while (it != m_units.end())
	{
		CUnit * unit = *it;

		SAFE_DEL(unit);
		it = m_units.erase(it);
	}

	ClearProjectiles();

	ClearParticleSystem();

	CGameConfig::RenderToTexture = true;

	loadWaves();

	m_lastDamageSource = -1;
	m_currentBonus = 0;
	m_comboUnitKind = UK_Unknown;

	/// Reset
	m_wavePos		= 0;
	m_time			= 0;

	m_gold = 0;
	m_souls = 0;

	m_slowGold = 0;
	m_slowSouls = 0;

	if (m_gate)
	{
		m_gate->reset();
		if (m_isEndless) m_gate->damageGate(m_damage);
	}
}

