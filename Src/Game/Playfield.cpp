{
	CUserProfile profile = __PROFILE();

	/// Level
	s32 difficulty;

	profile.Get( "unlock_level_easy", m_unlockLevelEasy );
	profile.Get( "unlock_level_normal", m_unlockLevelNormal );
	profile.Get( "unlock_level_hard", m_unlockLevelHard );

	profile.Get( "save_level", m_CurrentLevel );
	profile.Get( "save_day", m_CurrentDay );
	profile.Get( "save_difficulty", difficulty ); m_difficulty = (GameDifficulty)difficulty;	

	profile.Get( "enter_in_shop", m_EnterInShop );

	array<int> daysPerLevel = getNumberOfDaysPerLevel();
	if( m_CurrentLevel >= 0 && m_CurrentDay >= daysPerLevel[m_CurrentLevel] )
		m_CurrentDay = daysPerLevel[m_CurrentLevel] - 1;

	/// Cutscene
	s32 cutScene;
	profile.Get( "cutscene", cutScene );
	SetNextCutscene((CPlayfield::CutScene)cutScene);

	/// Other
	profile.Get( "gold", m_levelStats.Gold );
	profile.Get( "souls", m_levelStats.Souls );
	profile.Get( "killed", m_levelStats.Kills );

	profile.Get( "game_number", m_gameNumber );

	for( s32 i=0; i<WT_Count; i++ )
	{
		stringc weapon = "weapon_level_";
		weapon += i;
		profile.Get( weapon.c_str(), m_levelStats.WeaponLevel[i] );

		weapon = "weapon_available_";
		weapon += i;
		int val;
		profile.Get( weapon.c_str(), val );
		m_levelStats.WeaponAvailable[i] = val ? true : false;
	}

	profile.Get( "spell", m_levelStats.SpellAvailable );
}

