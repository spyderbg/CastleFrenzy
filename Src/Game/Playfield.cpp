void CPlayfield::pauseUnits()
{
	TUnitList::Iterator it = m_units.begin();
	while (it != m_units.end())
	{
		(*it)->freezeAnimation(true);
		it++;
	}

	m_castle->getAnimators().getFirstElem()->getTimelineCtrl()->setScale(0.0f);
	m_hydra->freezeAnimation(true);
	m_fireball->freezeAnimation(true);
	m_iceball->freezeAnimation(true);
	m_griffin->freezeAnimation(true);
	m_spell->freezeAnimation(true);

	ParticleSystemList::iterator iter = m_particleSystemList.begin();
	for(; iter != m_particleSystemList.end(); iter++)
	{
		(*iter)->Pause();
	}

	m_playPauseIcon->SetAnim(MENU_A_MENU_PAUSE_PLAY);
}

void CPlayfield::resumeUnits()
{
	TUnitList::Iterator it = m_units.begin();
	while (it != m_units.end())
	{
		(*it)->freezeAnimation(false);
		it++;
	}

	m_castle->getAnimators().getFirstElem()->getTimelineCtrl()->setScale(1.0f);
	m_hydra->freezeAnimation(false);
	m_fireball->freezeAnimation(false);
	m_iceball->freezeAnimation(false);
	m_griffin->freezeAnimation(false);
	m_spell->freezeAnimation(false);

	ParticleSystemList::iterator iter = m_particleSystemList.begin();
	for(; iter != m_particleSystemList.end(); iter++)
	{
		(*iter)->UnPause();
	}

	m_playPauseIcon->SetAnim(MENU_A_MENU_PLAY);
}

