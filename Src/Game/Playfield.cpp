void CPlayfield::ClearProjectiles (bool exit_level)
{
	for (int i = 0; i < m_projectiles.size(); ++i)
		delete m_projectiles[i];
	m_projectiles.clear();

	for (int i = 0; i < m_bombs.size(); ++i)
		if ( !m_bombs[i]->isForHelpMenu() || exit_level )
		{			
			SAFE_DEL( m_bombs[i] );
		}

	//more hardcoded and ugly but it works!!!!!!
	//first menu is initialized, then playfield, which calls reset and this.

	irr::core::array< CBomb * > temp;
	for (int i = 0; i < m_bombs.size(); ++i)
		if ( m_bombs[i] )
			temp.push_back( m_bombs[i] );

	m_bombs.clear();
	m_bombs = temp;
	temp.clear();
}

bool CPlayfield::checkCombo(int damageSource, UnitKind kind, int * money, const wchar_t ** text)
{
	m_challenge.unitDied(damageSource, kind);

	bool combo = false;
	*money = 0;
	*text = 0;

	if (m_lastDamageSource == UDS_GroundDrag && damageSource == UDS_WallHit ||
		m_lastDamageSource == UDS_WallHit && damageSource == UDS_GroundDrag)
	{
		if (m_comboUnitKind != kind)
			m_comboUnitKind = UK_Unknown;

		m_currentBonus += 2;

		*money = m_currentBonus;

		if (m_currentBonus >= 8)
		{
			combo = true;
			*text = _TXT(INGAME_COMBO);
			m_currentBonus = 0;
		}
	}
	else
	{
		m_currentBonus = 0;
		if (damageSource == UDS_GroundDrag || damageSource == UDS_WallHit)
		{
			m_comboUnitKind = kind;
		}
	}

	m_lastDamageSource = damageSource;
	return combo;
}

