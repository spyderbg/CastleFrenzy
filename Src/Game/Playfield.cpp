	u16 indices[] = {
		0, 1, 2,
		0, 2, 3,
		0, 3, 4,
		0, 4, 5,
		0, 5, 6,
		0, 6, 7,
		0, 7, 8
	};
	driver->drawVertexPrimitiveList(vertices, indices, 0, 7*3, 7, EVT_STANDARD, EPT_TRIANGLES, EIT_16BIT);
	//for (int i = 1; i < 9; ++i)
	//	driver->draw3DLine(o3d[0], o3d[i], 0xff000000);
	driver->setDepthRange(0.0f, 0.5f);
