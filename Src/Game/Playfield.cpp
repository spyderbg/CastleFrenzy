CUnit* CPlayfield::spawnUnit(const stringw & id, int slaves, float time, int unitId, bool intro)
{
	if (CGameConfig::DontSpawnUnits)
		return 0;

	f32 offset_min = -1.25f;
	f32 offset_max = 1.25f;
	f32 offset_len = offset_max - offset_min;

	const int lanes = 8;

	int lane = findFreeLane();
	allocateLane(lane);

	f32 offset = offset_min + offset_len * lane / (lanes - 1);

	UnitParameters* params = GetUnitParameters(id);
	CUnit * unit = new CUnit(params);
	unit->m_lane = lane;

	AddFrameEvent(FET_SpawnUnit, unit->getUnitKind());

	vector3df dir = m_path.getVector();
	vector3df up = vector3df(0, 1, 0);
	vector3df right = dir.crossProduct(up).normalize() * offset;

	line3df path = m_path;
	path.start += right;
	path.end += right * 0.5;
	unit->setPath(path);

	if (params->mindControl.size() > 0 && slaves > 0)
	{
		path.start -= 2.0f * path.getVector().normalize();
		for (int i = 0; i < slaves; ++i)
		{
			int slaveId = unitId + i + 1;
			CUnit* slave = spawnUnit(params->mindControl, 0, time, slaveId, false);
			slave->setMindControlMaster(unit);
			slave->setState(US_Walking);
			UnitTypeAndId utai = { stringToUnitType(params->mindControl), time + 0.001f, slaveId };
			m_extraSpawns.push_back(utai);
		}
	}

	if (params->rider.size() > 0)
	{
		int riderId = unitId + 1;
		unit->setRider(spawnUnit(params->rider, 0, time, riderId, false));
		unit->getRider()->setMount(unit);
		unit->getRider()->setState(US_Riding);
		ISceneNode* riderDummy = unit->getSceneNode()->getSceneNodeFromName("d_boar_rider");
		riderDummy->addChild(unit->getRider()->getSceneNode());
		float scale = unit->getSceneNode()->getScale().X;
		riderDummy->setScale(v3f(1.0f / scale, 1.0f / scale, 1.0f / scale));

		UnitTypeAndId utai = { stringToUnitType(params->rider), time + 0.001f, riderId };
		m_extraSpawns.push_back(utai);

		freeLane(unit->getRider()->m_lane);
		unit->getRider()->m_lane = unit->m_lane;
		allocateLane(unit->getRider()->m_lane);
		unit->getRider()->setPath(unit->getPath());
	}

	unit->start();
	m_units.push_back(unit);

	unit->m_positionInList = -1;
	unit->m_id = unitId;

	/// Set achievement 'No more Strangers'
	__ACHIEVEMENTS()->setValue( "No more Strangers", (1 << (s32)unit->getUnitKind()) );

	if (intro)
	{
		unit->setIntroUnit();
	}

	return unit;
}

