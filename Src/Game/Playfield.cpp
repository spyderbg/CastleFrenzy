void CPlayfield::SetMusic( s32 musicId, bool loop )
{
	CSoundManager* sm = __MGR_SOUNDS();

	if( musicId == m_CurrentMusic )
	{
		if( !sm->isSoundPlaying( m_CurrentMusic ) ) 
			if( !m_MusicPause )
				sm->play( m_CurrentMusic, loop );
	}
	else
	{
		sm->stop( m_CurrentMusic );

		m_PrevMusic		= m_CurrentMusic;
		m_CurrentMusic	= musicId;

		if( !m_MusicPause )
		{
			sm->play( m_CurrentMusic, loop );

			if( m_CurrentMusic == M_LEVEL_A_FAST )
				sm->play( M_LEVEL_A_FAST_INTRO, false );
		}
	}
}

void CPlayfield::SetNextMusic( s32 nextMusicId, bool loop )
{
	if( !IsMusicIdCorrect( nextMusicId ) )
		return;

	m_NextMusic		= nextMusicId;
	m_NextMusicLoop	= loop;

	if( !IsMusicIdCorrect( GetMusic() ) )
	{
		m_NextMusic		= -1;
		m_NextMusicLoop	= false;

		SetMusic( m_NextMusic, m_NextMusicLoop );
	}
}

///////////////////////////////////////////////////////////////////////

void CPlayfield::UpdateMusic()
{
	CSoundManager* sm = __MGR_SOUNDS();

	if( GetPlayState() == PS_CutScene )
	{
		s32 curMusic = GetMusic();
		s32 newMusic = curMusic;

		if( curMusic != M_LEVEL_A_SLOW )
			newMusic = M_LEVEL_A_SLOW;

		SetMusic( newMusic );
	}
	
	if( GetPlayState() == PS_Play )
	{
		s32 curMusic = GetMusic();
		s32 newMusic = curMusic;

		if( curMusic != M_LEVEL_A_SLOW )
			newMusic = M_LEVEL_A_SLOW;
		if( m_gate->getHealthRatio() <= 0.30f )
			newMusic = M_LEVEL_A_FAST;

		SetMusic( newMusic, true );
	}
	if( GetPlayState() == PS_MissionOver )
	{
		s32 idx = GetMusic();

		if( !sm->isSoundPlaying( idx ) )
		{
			SetMusic( -1 );
			if( idx == M_DEBRIEFING )
				SetMusic( idx, true );
		}
	}

	if( !IsMusicIdCorrect( GetMusic() ) )
		SetMusic( m_NextMusic, m_NextMusicLoop );
}


