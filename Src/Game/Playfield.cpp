void CPlayfield::updateIntroUnitCamera (f32 time)
{
	ICameraSceneNode* cam = __IRR_SCENE()->getActiveCamera();
	v3f camPos = cam->getAbsolutePosition();
	v3f camLook = cam->getTarget() - camPos;
	v3f camUp = cam->getUpVector();
	v3f camLeft = camUp.crossProduct(camLook);
	camUp = camLeft.crossProduct(camLook);

	camLeft.normalize();
	camUp.normalize();
	camLook.normalize();

	p2i mouse = p2i(130, 240);
	v3f targetPos = worldPosFromScreenAndDistance(mouse, 8.5f);
	quaternion targetRot = quaternion(0, -0.25 * PI, 0);

	float t = MIN(m_introTime / k_unitTransitionTime, 1.0f);
	//t = t * t;
	m_introUnit->setMPosition(m_introUnitStartPos + t * (targetPos - m_introUnitStartPos));
	quaternion q = quaternion().slerp(quaternion(), targetRot, t);
	m_introUnit->getSceneNode()->setRotation(q * m_introUnitStartRot);

	m_introUnit->UpdateShadow(time);

	if (!m_introGoingBack && m_introTime > k_unitTransitionTime + k_fadeTransitionTime)
	{
		m_backTouch->SetEnabled(true);

		p2i touch;
		m_backTouch->GetTouchPos_Current(touch.X, touch.Y);
		if (m_backTouch->IsNowReleased() && m_backTouch->IsPointInside(touch))
		{
			// go back to game
			m_introGoingBack = true;
			m_introTime = k_unitTransitionTime + k_fadeTransitionTime;
			m_introUnitStartPos = m_introUnit->getPath().end - m_introUnit->getPath().getVector().setLength(10.0f);

			__MGR_SOUNDS()->play( SFX_MENU_BACK );
			__MGR_SOUNDS()->play( SFX_ENEMY_TUTORIAL_APPEAR_OUT );
		}
	}

	m_introTime += m_introGoingBack ? -time : time;

	if (m_introGoingBack && m_introTime <= 0.0f)
	{
		m_introUnit->setMPosition(m_introUnitStartPos);
		m_touch->SetEnabled(true);
		delete m_backTouch;
		m_backTouch = 0;
		SetPlayState(PS_Play);

		if ( m_iceball ) 
			m_iceball->setOldState();

		m_introUnit->setVelocity(v3f(0, 0, 0));
	}
}

void CPlayfield::DrawIntroUnitCamera()
{
	float q = MIN(m_introTime / k_time, 1.0f);
	__IRR_DRIVER()->draw2DRectangle(0xff000000, r2i(0, 0, 480, q * 40));
	__IRR_DRIVER()->draw2DRectangle(0xff000000, r2i(0, 320 - q * 40, 480, 320));

	__IRR_DRIVER()->endScene2D();

	float t = MIN((m_introTime - k_unitTransitionTime) / k_fadeTransitionTime, 1.0f);
	//t = 1.0f - (1.0f - t) * (1.0f - t);
	int h = t * 240;

	// fade
	if (m_introTime > k_unitTransitionTime)
	{
		S3DVertex vertices[] = {
			S3DVertex(worldPosFromScreenAndDistance(p2i(  0, 160 - h / 2), 11.0f), v3f(), 0x9f000000, v2f()),
			S3DVertex(worldPosFromScreenAndDistance(p2i(480, 160 - h / 2), 11.0f), v3f(), 0x9f000000, v2f()),
			S3DVertex(worldPosFromScreenAndDistance(p2i(  0, 160 + h / 2), 11.0f), v3f(), 0x9f000000, v2f()),
			S3DVertex(worldPosFromScreenAndDistance(p2i(480, 160 + h / 2), 11.0f), v3f(), 0x9f000000, v2f())
		};
		u16 indices[] = { 0, 2, 1, 1, 2, 3 };
		SMaterial m;
		m.setMaterialType(EMT_TRANSPARENT_TEXTURE_VERTEX_ALPHA);
		m.setFlag(EMF_LIGHTING, false);
		__IRR_DRIVER()->setMaterial(m);
		__IRR_DRIVER()->setTransform(ETS_WORLD, matrix4::EM4CONST_IDENTITY);
		__IRR_DRIVER()->drawVertexPrimitiveList(vertices, indices, 0, 6, 2, EVT_STANDARD, EPT_TRIANGLES, EIT_16BIT);
	}

	__IRR_DRIVER()->beginScene2D();

	if (m_introTime > k_unitTransitionTime)
	{
		ASprite::PushClipRect(r2i(0, 160 - h / 2, 480, 160 + h / 2));

		// texts
		int txt = GetInfoText(m_introUnit);
		__FONT("MM_Help")->DrawString(_TXT_INT(txt), 240, 60, ASprite::HCENTER | ASprite::VCENTER);
		__FONT("MM_Help")->DrawWrappedText(_TXT_INT(txt + 1), 350, 180, 220, ASprite::HCENTER | ASprite::VCENTER);

		// back button
		p2i touch;
		m_backTouch->GetTouchPos_Current(touch.X, touch.Y);
		int x = m_backTouch->m_screenX + m_backTouch->m_screenW / 2;
		int y = m_backTouch->m_screenY + m_backTouch->m_screenH / 2;
		m_sprIngame->PaintAFrame(m_backTouch->IsActive() && m_backTouch->IsPointInside(touch) ?
			MENU_A_MENU_BACK_BUTTON_PRESSED : MENU_A_MENU_BACK_BUTTON_NORMAL, 0, x, y, 0, 0, 0);

		ASprite::PopClipRect();
	}
}

