void CPlayfield::Update_MissionOverCheck()
{
	if( m_gate->isDestroyed() )
		FaildMission();
	else if( m_wavePos >= m_waves.size() && m_units.getSize() == 0 )
		SuccessMission();
}

void CPlayfield::Update_MissionOverTimer()
{
	m_missionOverCountdown -= _time;

	if( m_missionOverCountdown <= 0 )
	{
		SetPlayState( PS_MissionOver );

		if( IsMissionSuccess() )
		{
			/// Set achievement 'Cash & Carry'
			__ACHIEVEMENTS()->setValue( "Cash & Carry", m_gold );

			m_levelStats.Gold += m_gold;
			m_levelStats.Souls += m_souls;
			m_gold = 0;
			m_souls = 0;
			m_slowGold = 0.0f;
			m_slowSouls = 0.0f;

			array<int> daysPerLevel = getNumberOfDaysPerLevel();
			s32 levelsNum = daysPerLevel.size() - 1;

			m_CurrentDay++;

			if( !m_isEndless && m_CurrentDay >= daysPerLevel[m_CurrentLevel] )
			{
				m_CurrentLevel++;

				if( !CGameConfig::UnlockAllLevels )
				{
					/// Set achievement 'Recruit', 'Soldier', 'True Defender'
					if( m_CurrentLevel >= levelsNum )
					{
						UnlockLevel( m_difficulty ) = levelsNum;

						if( m_difficulty == GD_Easy )
							__ACHIEVEMENTS()->setAchieved( "Recruit" );
						if( m_difficulty == GD_Normal )
							__ACHIEVEMENTS()->setAchieved( "Soldier" );
						if( m_difficulty == GD_Hard )
							__ACHIEVEMENTS()->setAchieved( "True Defender" );
					}
					else if( m_CurrentLevel > UnlockLevel( m_difficulty ) )
					{
						UnlockLevel( m_difficulty ) = m_CurrentLevel;
					}
				}

				m_isLevelOver = true;

				if (m_CurrentLevel >= levelsNum)
				{
					m_CurrentLevel = -1;
					m_CurrentDay = -1;

					CUserProfile profile = __PROFILE();
					int completed;
					profile.Get("GameCompletedState", completed);
					if (completed == 0)
						profile.Set("GameCompletedState", 1); // Go To About
				}
				else
				{
					m_CurrentDay = 0;
				}

				CPlayfield::GetInstance()->WriteProfileStats();
			}

			WriteProfileStats();		
		}
	}
}

