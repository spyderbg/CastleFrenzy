void CPlayfield::SetPlayState( PlayState state )
{
	if( m_PlayState == state )
		return;

	m_PlayState = state;

	if (m_PlayState == PS_IGM || m_PlayState == PS_MissionOverTimer || m_PlayState == PS_MissionOver || m_PlayState == PS_Restart )
		m_hudAlphaTarget = 0.0f;
	else
		m_hudAlphaTarget = 1.0f;

	switch( m_PlayState )
	{
	case PS_Begin:
		{
			ResetLevel();

			m_time = -999999;

			m_isLevelOver = false;
		}
		break;

	case PS_Restart:
		if( !m_isEndless )
			CPlayfield::GetInstance()->ReadProfileStats();
		fadeOut(1.0f);
		break;

	case PS_IGM:
	case PS_Pause:
		{
			pauseUnits();

			__MGR_SOUNDS()->stopAllSfx();
			__MGR_SOUNDS()->play( SFX_MENU_PAUSE );
		}
		break;

	case PS_Play:
		{
			resumeUnits();	
		}
		break;

	case PS_IntroUnitCamera:
		break;

	case PS_MissionOverTimer:
		if( IsMissionSuccess() )
		{
			if (m_challenge.getType() != CT_None && m_challenge.isChallengeCompleted())
				SetMusic( M_LEVEL_COMPLETE_WITH_CHALENGE );
			else
				SetMusic( M_LEVEL_COMPLETE_NO_CHALENGE );
		}
		else
		{
			SetMusic( M_LOSE );
		}
		break;

	case PS_MissionOver:
		__MGR_SOUNDS()->stopAllSfx();
		SetNextMusic( M_DEBRIEFING, true );
		break;

	case PS_EnterIGM:
		{
			PauseMusic();
		}
		break;
	case PS_ExitIGM:
		{
			SetPlayState( PS_Play );
			ResumeMusic();
		}
		break;

	case PS_Shop:
		SetMusic( -1 );
		__MGR_STATES()->pushState<GS_Shop>();
		break;

	case PS_CutScene:
		break;
	}

	if (IsLevelLoaded())
	{
		if (m_PlayState == PS_Play)
		{
			m_fireball->getTouch()->SetEnabled(true);
			m_iceball->getTouch()->SetEnabled(true);
			m_griffin->getTouch()->SetEnabled(true);
		}
		else
		{
			m_fireball->getTouch()->SetEnabled(false);
			m_iceball->getTouch()->SetEnabled(false);
			m_griffin->getTouch()->SetEnabled(false);
		}
	}
}

