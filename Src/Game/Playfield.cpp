struct SAmbientColorKey
{
	SColorf	color;
	f32		time;
};

SAmbientColorKey sky_key[] = 
{
	{SColorf(1.00f, 1.00f, 1.00f, 1.00f), 0.00f},

	{SColorf(1.00f, 1.00f, 1.00f, 1.00f), 0.15f},
	{SColorf(1.00f, 1.00f, 1.00f, 1.00f), 0.70f}, // 30
	{SColorf(1.00f, 0.80f, 0.60f, 1.00f), 0.85f}, // 24
	{SColorf(0.45f, 0.65f, 0.75f, 1.00f), 1.00f}, // 20
};

const int sky_key_size = sizeof(sky_key) / sizeof(SAmbientColorKey);

void CPlayfield::SetDayTime( f32 day_time )
{
	if( day_time == m_DayTime )
		return; 
	
	m_DayTime = day_time;

	if( m_SceneLight == NULL )
		return;

	SColorf skyColor;

	for (int i = 0; i < sky_key_size; i++)
	{
		if (m_DayTime <= sky_key[i].time)
		{
			int k2 = i;
			int k1 = i - 1;

			if (k2 == 0)
			{
				skyColor = sky_key[0].color;
			}
			else
			{
				skyColor = sky_key[k1].color.getInterpolated(sky_key[k2].color, 
					(sky_key[k2].time - m_DayTime) / (sky_key[k2].time - sky_key[k1].time) );
			}
			break;
		}
	}

	SLight & light = m_SceneLight->getLightData();
	light.AmbientColor = skyColor;

}

