bool CPlayfield::checkUnitTouch(CUnit * unit)
{
	rect<s32> r(-45, -25, 25, 45);
	if (unit->getUnitKind() == UK_Shaman)
		r = r2i(-35, -45, 35, 45);
	else if (unit->getUnitKind() == UK_Elf || unit->getUnitKind() == UK_Troll)
		r = r2i(-45, -45, 25, 45);
	else if (unit->getUnitKind() == UK_Boar)
		r = r2i(-45, -25, 35, 45);
	r += unit->getScreenPosition();

	position2di p2;
	getTouch()->GetTouchPos_Current(p2.X, p2.Y);

	if( isNowActivatedTouch() )
		return r.isPointInside(p2);

	position2di p1;
	getTouch()->GetTouchPos_Prev(p1.X, p1.Y);

	if (r.isPointInside(p1) || r.isPointInside(p2))
		return true;

	line2di line(p1.X, p1.Y, p2.X, p2.Y);

	line2di d1(r.UpperLeftCorner.X,  r.UpperLeftCorner.Y,  r.LowerRightCorner.X,  r.LowerRightCorner.Y);
	line2di d2(r.UpperLeftCorner.X,  r.LowerRightCorner.Y,  r.LowerRightCorner.X, r.UpperLeftCorner.Y);
	
	vector2di tmp;
	if (line.intersectWith(d1, tmp) || line.intersectWith(d2, tmp))
		return true;

	return false;
}

